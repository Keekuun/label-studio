// 辅助函数
export function getAllComponentMetas(): ComponentMeta[] {
  return componentMetas;
}

export function getComponentMeta(type: string): ComponentMeta | undefined {
  return componentMetas.find((meta) => meta.type === type);
}

export function getComponentMetasByCategory(category: "object" | "control" | "visual"): ComponentMeta[] {
  return componentMetas.filter((meta) => meta.category === category);
}

export function getComponentMetasByGroup(group: string): ComponentMeta[] {
  return componentMetas.filter((meta) => meta.group === group);
}
